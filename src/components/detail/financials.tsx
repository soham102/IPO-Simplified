import { formatDate, formatNumber, formatSignedPct } from "@/lib/format";
import { computeYearMetrics, revenueCagr, type YearMetrics } from "@/lib/metrics";
import type { Citation, Ipo, Unit } from "@/lib/types";
import { FinancialBarChart } from "@/components/charts/financial-bar-chart";
import { Detailed } from "@/components/ui/detail-level";
import { Disclosure } from "@/components/ui/disclosure";
import { EmptyState } from "@/components/ui/empty-state";
import { VerificationTag } from "@/components/ui/indicators";
import { SourceRef } from "@/components/ui/source-ref";
import { Term } from "@/components/ui/term";
import { Callout, Panel, SectionTitle } from "./section";

interface MetricRow {
  key: string;
  label: React.ReactNode;
  unit: Unit;
  get: (m: YearMetrics) => number | null;
  signed?: boolean;
  derived?: boolean;
  detailedOnly?: boolean;
  what: string;
  why: string;
}

const ROWS: MetricRow[] = [
  { key: "revenue", label: "Revenue from operations", unit: "INR_CRORE", get: (m) => m.revenue, what: "Money earned from selling the company's products or services.", why: "Shows the size of the business and whether demand is growing." },
  { key: "growth", label: "Revenue growth", unit: "PERCENT", get: (m) => m.revenueGrowth, signed: true, derived: true, what: "Change in revenue versus the previous full year.", why: "Steady growth suggests rising demand; erratic or slowing growth deserves a closer look." },
  { key: "pat", label: "Profit after tax", unit: "INR_CRORE", get: (m) => m.pat, what: "What's left after all expenses, interest and taxes. Negative means a loss.", why: "Profit is what ultimately belongs to shareholders." },
  { key: "margin", label: "Profit margin", unit: "PERCENT", get: (m) => m.patMargin, derived: true, what: "Profit after tax ÷ revenue.", why: "Higher margins mean the company keeps more of each rupee of sales and has more buffer if costs rise." },
  { key: "ocf", label: <Term id="ocf">Operating cash flow</Term>, unit: "INR_CRORE", get: (m) => m.operatingCashFlow, what: "Cash actually generated by day-to-day operations.", why: "Profit that never turns into cash is a warning sign; negative cash flow may mean the company needs more funding." },
  { key: "borrowings", label: "Total borrowings", unit: "INR_CRORE", get: (m) => m.borrowings, what: "Loans and other debt owed by the company.", why: "More debt means more interest to pay and more risk if business slows." },
  { key: "de", label: <Term id="debt-to-equity">Debt-to-equity</Term>, unit: "RATIO", get: (m) => m.debtToEquity, derived: true, detailedOnly: true, what: "Borrowings ÷ net worth.", why: "Above about 1–2x, debt starts to dominate the balance sheet for most non-financial businesses." },
  { key: "networth", label: "Net worth", unit: "INR_CRORE", get: (m) => m.netWorth, detailedOnly: true, what: "Assets minus liabilities: the shareholders' stake on paper.", why: "Used to judge how much debt the company carries relative to its own funds." },
  { key: "eps", label: <Term id="eps">Diluted EPS</Term>, unit: "INR", get: (m) => m.dilutedEps, what: "Profit per share, counting shares that could be created from options.", why: "Used to calculate the P/E ratio. Shown on pre-issue shares as in the offer document." },
];

function cell(v: number | null, unit: Unit, signed?: boolean) {
  if (v == null) return <span className="text-xs text-ink-3 italic">Data unavailable</span>;
  const text = signed ? formatSignedPct(v) : formatNumber(v, unit, unit === "RATIO" ? 2 : 1);
  return <span className={v < 0 ? "text-risk" : undefined}>{text}</span>;
}

function Row({ r, metrics, revenueLabel }: { r: MetricRow; metrics: YearMetrics[]; revenueLabel: string }) {
  return (
    <tr className="border-t border-line align-top">
      <th scope="row" className="sticky left-0 z-[1] w-40 bg-surface py-3 pr-4 text-left font-normal sm:w-auto">
        <span className="font-medium text-ink">{r.key === "revenue" ? revenueLabel : r.label}</span>
        {r.derived && <span className="ml-1.5 text-[11px] text-ink-3">calculated</span>}
        <Disclosure summary="What this means" className="mt-1">
          <p>{r.what}</p>
          <p className="mt-1"><span className="font-medium text-ink">Why it matters: </span>{r.why}</p>
        </Disclosure>
      </th>
      {metrics.map((m, i) => (
        <td key={m.period} className="py-3 pl-4 text-right whitespace-nowrap num">
          {r.key === "growth" && i === 0 ? <span className="text-ink-3" title="No earlier year to compare with">—</span> : cell(r.get(m), r.unit, r.signed)}
        </td>
      ))}
    </tr>
  );
}

export function FinancialsSection({ ipo }: { ipo: Ipo }) {
  const fs = ipo.financials;
  const metrics = computeYearMetrics(fs);
  if (!fs || metrics.length === 0) {
    return (
      <div>
        <SectionTitle title="Financial health" />
        <EmptyState title="Financial statements not yet available">
          We don&apos;t have verified financial figures for this company yet. We won&apos;t estimate them.
        </EmptyState>
      </div>
    );
  }
  const cagr = revenueCagr(metrics.filter((m) => m.revenue != null));
  const cite: Citation | null = metrics[0]!.source.revenue.citation;
  const statuses = new Set(metrics.flatMap((m) => [m.source.revenue.status, m.source.pat.status]));
  const partial = fs.years.filter((y) => y.months !== 12);
  const revenueLabel = fs.revenueBasis === "total_income" ? "Total income" : "Revenue from operations";

  return (
    <div className="space-y-6">
      <SectionTitle
        title="Financial health"
        intro="How big the business is, whether it makes money, whether that money turns into cash, and how much it owes."
      />
      <Callout>
        <span className="font-medium text-ink">{fs.basis === "consolidated" ? "Consolidated" : "Standalone"} figures</span>{" "}
        (<Term id="consolidated">what&apos;s the difference?</Term>), Indian financial years ending 31 March, ₹ crore unless stated.
        {fs.note && <> {fs.note}</>} <SourceRef slug={ipo.slug} citation={cite} className="align-middle" />
        <span className="ml-1.5 inline-flex gap-1 align-middle">{[...statuses].map((s) => <VerificationTag key={s} status={s} />)}</span>
        {partial.length > 0 && (
          <p className="mt-1">Partial periods ({partial.map((p) => p.period).join(", ")}) are excluded from growth calculations.</p>
        )}
      </Callout>

      <div className="grid gap-4 lg:grid-cols-2">
        <Panel title={revenueLabel} action={cagr != null ? <span className="text-sm text-ink-2 num">CAGR {formatNumber(cagr, "PERCENT")}</span> : undefined}>
          <FinancialBarChart title={revenueLabel} unit="INR_CRORE" data={metrics.map((m) => ({ period: m.period, value: m.revenue }))} />
        </Panel>
        <Panel title="Profit after tax">
          <FinancialBarChart title="Profit after tax" unit="INR_CRORE" data={metrics.map((m) => ({ period: m.period, value: m.pat }))} />
        </Panel>
      </div>

      <Panel title="Year by year">
        <div className="-mx-5 overflow-x-auto px-5 sm:-mx-6 sm:px-6">
          <table className="w-full min-w-[480px] text-sm">
            <caption className="sr-only">Financial metrics by financial year</caption>
            <thead>
              <tr className="text-xs text-ink-3">
                <th scope="col" className="sticky left-0 z-[1] bg-surface pb-2 text-left font-medium">Metric</th>
                {metrics.map((m) => (
                  <th key={m.period} scope="col" className="pb-2 pl-4 text-right font-medium">
                    {m.period}
                    <span className="block font-normal">to {formatDate(m.source.periodEnd)}</span>
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {ROWS.filter((r) => !r.detailedOnly).map((r) => (
                <Row key={r.key} r={r} metrics={metrics} revenueLabel={revenueLabel} />
              ))}
              <Detailed>
                {ROWS.filter((r) => r.detailedOnly).map((r) => (
                  <Row key={r.key} r={r} metrics={metrics} revenueLabel={revenueLabel} />
                ))}
              </Detailed>
            </tbody>
          </table>
        </div>
        <p className="mt-2 text-xs text-ink-3 sm:hidden">Scroll sideways to see all years →</p>
        <p className="mt-3 text-xs text-ink-3">
          &quot;Calculated&quot; rows are derived by IPO Simplified from the reported figures. Growth isn&apos;t shown for the first
          year or when the previous year was zero or negative. Switch to Detailed mode for debt-to-equity and net worth.
        </p>
      </Panel>
    </div>
  );
}
