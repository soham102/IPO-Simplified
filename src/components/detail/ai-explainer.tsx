"use client";

import { useState } from "react";
import { Loader2, Sparkles } from "lucide-react";
import { TOPIC_LABEL, TOPICS, type Explanation, type Topic } from "@/lib/ai/topics";
import { SourceRef } from "@/components/ui/source-ref";
import { cn } from "@/lib/cn";

type State = { kind: "idle" } | { kind: "loading"; topic: Topic } | { kind: "done"; data: Explanation } | { kind: "error"; message: string };

/**
 * "Explain this to me" panel. Uses Claude when the server has an API key,
 * otherwise the rule-based explainer. Facts, interpretations and unknowns
 * are always shown separately, with sources.
 */
export function AiExplainer({ slug, enabled }: { slug: string; enabled: boolean }) {
  const [state, setState] = useState<State>({ kind: "idle" });

  async function run(topic: Topic) {
    setState({ kind: "loading", topic });
    try {
      const res = await fetch("/api/explain", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ slug, topic }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error ?? `Request failed (${res.status})`);
      setState({ kind: "done", data: json as Explanation });
    } catch (e) {
      setState({ kind: "error", message: e instanceof Error ? e.message : "Something went wrong" });
    }
  }

  const activeTopic = state.kind === "loading" ? state.topic : state.kind === "done" ? state.data.topic : null;

  return (
    <section className="card overflow-hidden" aria-labelledby="explain-heading">
      <div className="border-b border-line bg-sunken px-5 py-4 sm:px-6">
        <h2 id="explain-heading" className="flex items-center gap-2 font-sans text-base font-semibold">
          <Sparkles className="size-4 text-brand" aria-hidden />
          Explain it to me
        </h2>
        <p className="mt-1 text-sm text-ink-2">
          {enabled
            ? "Get a plain-English walkthrough generated by AI from the cited facts on this page only. AI can make mistakes, so check the linked sources."
            : "Get a plain-English walkthrough built from our rule-based analysis. (AI explanations are switched off on this deployment.)"}
        </p>
        <div className="mt-3 flex flex-wrap gap-2">
          {TOPICS.map((t) => (
            <button
              key={t}
              type="button"
              disabled={state.kind === "loading"}
              onClick={() => run(t)}
              aria-pressed={activeTopic === t}
              className={cn(
                "inline-flex items-center gap-1.5 rounded-full border px-3 py-1.5 text-sm font-medium transition-colors disabled:opacity-60",
                activeTopic === t ? "border-brand bg-brand text-on-brand" : "border-line bg-surface text-ink-2 hover:text-ink",
              )}
            >
              {state.kind === "loading" && state.topic === t && <Loader2 className="size-3.5 animate-spin" aria-hidden />}
              {TOPIC_LABEL[t]}
            </button>
          ))}
        </div>
      </div>

      <div className="px-5 py-5 sm:px-6" aria-live="polite">
        {state.kind === "idle" && <p className="text-sm text-ink-3">Choose a topic above.</p>}
        {state.kind === "loading" && (
          <div className="space-y-2" role="status">
            <span className="sr-only">Generating explanation…</span>
            <div className="h-4 w-3/4 animate-pulse rounded bg-sunken" />
            <div className="h-4 w-2/3 animate-pulse rounded bg-sunken" />
            <div className="h-4 w-1/2 animate-pulse rounded bg-sunken" />
          </div>
        )}
        {state.kind === "error" && (
          <p role="alert" className="rounded-lg bg-risk-soft px-3 py-2 text-sm text-risk">
            Couldn&apos;t generate an explanation: {state.message}
          </p>
        )}
        {state.kind === "done" && <ExplanationView data={state.data} slug={slug} />}
      </div>
    </section>
  );
}

function ExplanationView({ data, slug }: { data: Explanation; slug: string }) {
  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center gap-2 text-xs text-ink-3">
        <span className={cn("rounded-full px-2 py-0.5 font-medium", data.mode === "ai" ? "bg-brand-soft text-brand" : "bg-sunken text-ink-2")}>
          {data.mode === "ai" ? `AI-generated${data.model ? ` · ${data.model}` : ""}` : "Rule-based"}
        </span>
        <span>{new Date(data.generatedAt).toLocaleString("en-IN")}</span>
      </div>
      {data.notice && <p className="rounded-lg bg-warn-soft px-3 py-2 text-sm text-ink">{data.notice}</p>}
      <p className="text-ink">{data.summary}</p>
      <Block title="Facts" hint="What the sources say" items={data.facts} slug={slug} />
      <Block title="Interpretation" hint={data.mode === "ai" ? "What it might mean (AI's reading, based on the facts cited)" : "How our published rules label it"} items={data.interpretations} slug={slug} />
      <div>
        <h3 className="font-sans text-sm font-semibold">Unknowns</h3>
        <p className="text-xs text-ink-3">What the available evidence can&apos;t tell you</p>
        {data.unknowns.length ? (
          <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-ink-2">
            {data.unknowns.map((u) => (
              <li key={u}>{u}</li>
            ))}
          </ul>
        ) : (
          <p className="mt-2 text-sm text-ink-3 italic">None flagged.</p>
        )}
      </div>
      <p className="border-t border-line pt-3 text-xs text-ink-3">Educational explanation only. This is not a recommendation to apply for or avoid this IPO.</p>
    </div>
  );
}

function Block({ title, hint, items, slug }: { title: string; hint: string; items: Explanation["facts"]; slug: string }) {
  return (
    <div>
      <h3 className="font-sans text-sm font-semibold">{title}</h3>
      <p className="text-xs text-ink-3">{hint}</p>
      {items.length ? (
        <ul className="mt-2 space-y-2">
          {items.map((i, idx) => (
            <li key={idx} className="text-sm text-ink-2">
              {i.text}{" "}
              {i.citations.map((c, j) => (
                <SourceRef key={j} slug={slug} citation={c} className="mr-1 align-middle" />
              ))}
            </li>
          ))}
        </ul>
      ) : (
        <p className="mt-2 text-sm text-ink-3 italic">Nothing to show.</p>
      )}
    </div>
  );
}
